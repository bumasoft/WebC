// webc/pwa.h — the manifest, the worker, and the two head lines.
//
// The worker is a string with one substitution: the cache name. That is deliberate — a worker is
// JavaScript the app cannot debug in C, so the less of it the framework writes the better, and
// what it does write is two rules a reader can check in a minute.
#include <errno.h>
#include <sys/stat.h>

#include <webc/pwa.h>

static WPwa g_pwa;

void pwa_init(const WPwa *cfg) {
  g_pwa = cfg ? *cfg : (WPwa){0};
  if (!g_pwa.short_name) g_pwa.short_name = g_pwa.name;
  if (!g_pwa.background) g_pwa.background = g_pwa.theme ? g_pwa.theme : "#ffffff";
  if (!g_pwa.start) g_pwa.start = "/";
  if (!g_pwa.scope) g_pwa.scope = "/";
  if (!g_pwa.offline) g_pwa.offline = "/offline";
  if (!g_pwa.theme) g_pwa.theme = "#ffffff";
}

bool pwa_configured(void) { return g_pwa.name && *g_pwa.name; }
const WPwa *pwa_config(void) { return &g_pwa; }

// The build's identity. A deploy is a new module file, so the module's size and mtime are the
// truthful answer and need no cooperation from the toolchain; `WEBC_BUILD_ID` overrides it for a
// CI that already knows the commit.
str pwa_build_id(void) {
  const char *env = getenv("WEBC_BUILD_ID");
  if (env && *env) return str_lit(env);
  struct stat st;
  if (stat(WC_WASM_PATH, &st) == 0) {
    Buf b;
    buf_init(&b, wc_arena_get(), 32);
    buf_printf(&b, "%llx%llx", (unsigned long long)st.st_size, (unsigned long long)st.st_mtime);
    return buf_str(&b);
  }
  // no module on disk (a server-only app, or a test): the binary's own build is the identity
  return str_lit("dev");
}

Text pwa_cache_name(void) {
  Buf b;
  buf_init(&b, wc_arena_get(), 32);
  buf_puts(&b, "webc-");
  buf_putstr(&b, pwa_build_id());
  return buf_cstr(&b);
}

// `json_escape` returns the value *with* its quotes, so the manifest is assembled from values and
// never from format strings with quotes baked in — the difference shows up the first time an app
// names itself with a quote in it.
static void manifest_field(Buf *b, const char *key, str value, bool first) {
  if (!first) buf_putc(b, ',');
  buf_printf(b, "\"%s\":", key);
  buf_putstr(b, json_escape(b->a ? b->a : wc_arena_get(), value));
}

Response pwa_manifest(void) {
  Arena *a = wc_arena_get();
  Buf b;
  buf_init(&b, a, 512);
  const WPwa *c = &g_pwa;
  buf_putc(&b, '{');
  manifest_field(&b, "name", str_lit(c->name ? c->name : "WebC app"), true);
  manifest_field(&b, "short_name", str_lit(c->short_name ? c->short_name : ""), false);
  manifest_field(&b, "start_url", str_lit(c->start), false);
  manifest_field(&b, "scope", str_lit(c->scope), false);
  manifest_field(&b, "display", str_lit(c->standalone ? "standalone" : "browser"), false);
  manifest_field(&b, "theme_color", str_lit(c->theme), false);
  manifest_field(&b, "background_color", str_lit(c->background), false);
  buf_puts(&b, ",\"icons\":[");
  bool first = true;
  if (c->icon) {
    buf_puts(&b, "{\"src\":");
    buf_putstr(&b, json_escape(a, str_lit(c->icon)));
    buf_puts(&b, ",\"sizes\":\"192x192\",\"type\":\"image/png\"}");
    first = false;
  }
  if (c->mask_icon) {
    if (!first) buf_putc(&b, ',');
    buf_puts(&b, "{\"src\":");
    buf_putstr(&b, json_escape(a, str_lit(c->mask_icon)));
    buf_puts(&b, ",\"sizes\":\"512x512\",\"type\":\"image/png\",\"purpose\":\"maskable\"}");
  }
  buf_puts(&b, "]}");
  str body = buf_str(&b);
  Response r = res_bytes(200, "application/manifest+json", body.p, body.n);
  res_header(&r, "Cache-Control", "no-cache");
  return r;
}

// The worker. Two rules, said out loud:
//   * a navigation goes to the network first and falls back to the offline page — a page you can
//     read beats a cached page that lies;
//   * the module, the bridge and the icons are cache-first, because they are pinned to a build
//     and the cache name is that build.
// Everything else is left alone: a POST, an API call, an SSE stream must never be served from a
// cache, and a worker that tries is a worker that breaks the app's live updates.
Response pwa_worker(void) {
  Arena *a = wc_arena_get();
  Buf b;
  buf_init(&b, a, 2048);
  const WPwa *c = &g_pwa;
  buf_puts(&b, "// generated by webc/pwa.h — replaceable: delete this route and write your own\n");
  buf_printf(&b, "const CACHE = 'webc-%.*s';\n", (int)pwa_build_id().n, pwa_build_id().p);
  buf_printf(&b, "const OFFLINE = '%s';\n", c->offline);
  buf_puts(&b,
           "self.addEventListener('install', (e) => {\n"
           "  e.waitUntil(caches.open(CACHE).then((c) => c.addAll([OFFLINE])).then(() => self.skipWaiting()));\n"
           "});\n"
           "self.addEventListener('activate', (e) => {\n"
           "  e.waitUntil(caches.keys()\n"
           "    .then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k))))\n"
           "    .then(() => self.clients.claim()));\n"
           "});\n"
           "self.addEventListener('fetch', (e) => {\n"
           "  const req = e.request;\n"
           "  if (req.method !== 'GET') return;\n"
           "  const url = new URL(req.url);\n"
           "  if (url.origin !== location.origin) return;\n"
           "  const isAsset = /\\/(app\\.wasm|webc\\.js|dev\\.js|icon-[^/]*)$/.test(url.pathname);\n"
           "  if (isAsset) {\n"
           "    e.respondWith(caches.open(CACHE).then((c) =>\n"
           "      c.match(req).then((hit) => hit || fetch(req).then((res) => { c.put(req, res.clone()); return res; }))));\n"
           "    return;\n"
           "  }\n"
           "  if (req.mode === 'navigate') {\n"
           "    e.respondWith(fetch(req).catch(() => caches.match(OFFLINE)));\n"
           "  }\n"
           "});\n");
  str body = buf_str(&b);
  Response r = res_bytes(200, "text/javascript; charset=utf-8", body.p, body.n);
  res_header(&r, "Cache-Control", "no-cache");
  return r;
}

// The two lines a head needs. The `<link rel=manifest>` is what makes the app installable at all,
// and the theme colour is what colours the browser's chrome — both facts the config already has.
void pwa_head(void) {
  if (!pwa_configured()) return;
  webc_head_link(str_lit("manifest"), str_lit("/manifest.webmanifest"));
  Buf tag;
  buf_init(&tag, wc_arena_get(), 96);
  buf_printf(&tag, "<meta name=\"theme-color\" content=\"%s\">", g_pwa.theme);
  webc_head_html(buf_str(&tag));
  buf_init(&tag, wc_arena_get(), 96);
  buf_printf(&tag, "<link rel=\"apple-touch-icon\" href=\"%s\">",
             g_pwa.icon ? g_pwa.icon : "/icon-192.png");
  webc_head_html(buf_str(&tag));
}
