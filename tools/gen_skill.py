#!/usr/bin/env python3
"""Generate the WebC skill's reference leaves from the documentation.

The skill is a router: `skills/webc/SKILL.md` is written by hand (it is the part that
decides *what to do*), and everything under `skills/webc/references/` is generated here
from the pages the project already maintains — `docs/reference.md`, the site's guides,
and `webc lint --rules`.

Why generated: a skill that teaches a retired call is worse than no skill at all — it is a
language nobody can compile, delivered with confidence. The
repository already believes this about budgets (`api.txt`, `make budget`); this is the
same rule applied to prose. `make skill-check` fails when the generated leaves are stale
or when the skill names a retired spelling.

    python3 tools/gen_skill.py            # write skills/webc/references/
    python3 tools/gen_skill.py --check    # exit 1 when anything would change
"""

import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "skills", "webc", "references")
REFERENCE = os.path.join(ROOT, "docs", "reference.md")
CONTENT = os.path.join(ROOT, "website", "src", "content")

# One leaf per question an agent actually asks. `sources` are whole pages (the site's
# guides, which are already sized for reading); `sections` are anchors in
# docs/reference.md, which is 3 392 lines and must never be loaded whole.
LEAVES = [
    ("core-and-strings", "Strings, formatting, scopes, errors, Vec and Map — the vocabulary",
     [],
     ["house-rules", "core", "collections"]),
    ("models-and-orm", "Models, fields, migrations, filters, relations, pages, trees",
     ["guides/models.md", "guides/orm.md"],
     ["models", "database"]),
    ("http-and-routes", "Routes, responses, cookies, streaming, middleware, gzip, ranges",
     ["guides/http.md"],
     ["http", "middleware"]),
    ("views-and-signals", "The DOM builder, signals, effects, parts, components, children",
     ["guides/signals.md", "guides/components.md"],
     ["signals", "dom"]),
    ("client-and-wasm", "The browser half: mount, actions, live bindings, the JS bridge",
     ["guides/live.md"],
     ["bridge"]),
    ("data-and-sql", "Postgres and MySQL, migrations per dialect, Redis, the query cache",
     ["guides/data.md", "guides/mysql.md"],
     []),
    ("auth", "Passwords, signed session cookies, the secret, and testing a login flow",
     ["guides/auth.md"],
     ["auth"]),
    ("forms", "Form parsing, validation, and a form drawn from a model",
     ["guides/forms.md"],
     ["json-and-forms"]),
    ("stdlib", "The twenty opt-in modules and what each one costs",
     ["guides/stdlib.md"],
     ["#12i."]),
    ("testing", "TEST blocks, assertions, fixtures, request without a socket",
     ["guides/testing.md"],
     ["testing"]),
    ("concurrency", "Green threads, channels, select, timers, mutexes, wait groups",
     [],
     ["concurrency"]),
    ("ops-and-deploy", "Logs, metrics, limits, graceful drain, deploying the binary",
     ["guides/deploy.md"],
     ["ops", "limits"]),
    ("cli", "Every webc command, the language server, the MCP server and the contract an agent tool reads",
     [],
     ["cli", "lsp", "vscode", "mcp", "agents"]),
]

BANNER = (
    "<!-- generated by `make skill` (tools/gen_skill.py) — edit the sources, not this file -->\n"
)


def split_reference(text):
    """docs/reference.md -> {anchor-or-slug: (level, title, body)}.

    Headings carry their anchor as `<a name="x"></a>`, which is how the site links to
    them; a heading without one is keyed by its title, lowercased with dashes.
    """
    lines = text.splitlines(keepends=True)
    blocks = {}
    current = None
    head = re.compile(r"^(#{2,4})\s+(.*)$")
    anchor = re.compile(r'<a name="([^"]+)"></a>')
    for line in lines:
        m = head.match(line)
        if m:
            level = len(m.group(1))
            title = m.group(2).strip()
            a = anchor.search(title)
            key = a.group(1) if a else re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
            current = key
            blocks[key] = {"level": level, "title": anchor.sub("", title).strip(), "body": []}
            continue
        if current:
            blocks[current]["body"].append(line)
    return blocks


def resolve(blocks, want):
    """An anchor, or `#text` for a heading whose title contains `text` (some sections
    are numbered without an anchor)."""
    if not want.startswith("#"):
        return want if want in blocks else None
    needle = want[1:]
    for key, b in blocks.items():
        if needle in b["title"]:
            return key
    return None


def extract(blocks, anchors):
    """Every requested section, with its sub-headings, in file order."""
    order = list(blocks.keys())
    out = []
    for a in anchors:
        key = resolve(blocks, a)
        if key is None:
            sys.stderr.write(f"gen_skill: no section matching {a!r} in docs/reference.md\n")
            sys.exit(1)
        start = order.index(key)
        level = blocks[key]["level"]
        body = ["".join(blocks[key]["body"])]
        for k in order[start + 1:]:
            if blocks[k]["level"] <= level:
                break
            body.append("".join(blocks[k]["body"]))
        out.append((blocks[key]["title"], "".join(body)))
    return out


def guide_page(rel):
    path = os.path.join(CONTENT, rel)
    with open(path, encoding="utf-8") as f:
        text = f.read()
    # drop the site's own front matter, if any
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4:]
    return text.strip() + "\n"


def lint_rules():
    """The retired spellings, straight from the gate that enforces them."""
    exe = os.path.join(ROOT, "build", "webc")
    if not os.path.exists(exe):
        sys.stderr.write("gen_skill: build/webc is missing — run `make` first\n")
        sys.exit(1)
    out = subprocess.run([exe, "lint", "--rules"], capture_output=True, text=True)
    if out.returncode != 0:
        sys.stderr.write(out.stderr)
        sys.exit(1)
    return out.stdout


def orphans(blocks):
    """Top-level reference sections no leaf quotes.

    A skill is a router, and a router with a dead end is worse than no skill: the reader is
    told "read the leaves" and the answer is in a section nobody copied. This is what turned
    "auth is missing" into a build error instead of a bug report from an agent.
    """
    order = list(blocks.keys())
    claimed = set()
    for _name, _what, _guides, anchors in LEAVES:
        for a in anchors:
            key = resolve(blocks, a)
            if key is None:
                continue
            i = order.index(key)
            # walk back to the enclosing top-level section
            for k in reversed(order[: i + 1]):
                if blocks[k]["level"] == 2:
                    claimed.add(k)
                    break
    return [k for k in order if blocks[k]["level"] == 2 and k not in claimed]


def build():
    with open(REFERENCE, encoding="utf-8") as f:
        blocks = split_reference(f.read())
    files = {}
    for name, what, guides, anchors in LEAVES:
        parts = [BANNER, f"# {what}\n",
                 "Generated from the project's own documentation; read this instead of the\n"
                 "whole reference. Sections are quoted verbatim from `docs/reference.md` and\n"
                 "`website/src/content/guides/`.\n"]
        sections = extract(blocks, anchors)
        body = []
        index = []   # (line number, description)
        head = [BANNER, f"# {what}\n",
                "Generated from the project's own documentation. Read the part you need — a\n"
                "span, not the whole file; the numbers below are exact because this file is\n"
                "generated and never edited.\n\n## What is in this file\n"]
        line_after_head = len("".join(head).splitlines()) + 1
        cursor = line_after_head
        for g in guides:
            text = guide_page(g)
            index.append((cursor, "guide `website/src/content/" + g + "`"))
            body.append(text)
            cursor += text.count("\n")
        for title, chunk in sections:
            text = f"\n<!-- docs/reference.md: {title} -->\n{chunk}"
            index.append((cursor + 2, "`docs/reference.md` — " + title))
            body.append(text)
            cursor += text.count("\n")
        parts = head + [f"- line {n}: {d}\n" for n, d in index] + ["\n---\n\n"]
        files[f"{name}.md"] = "".join(parts) + "\n".join(body).strip() + "\n"
    files["traps.md"] = BANNER + lint_rules().strip() + "\n"
    dead = orphans(blocks)
    if dead:
        sys.stderr.write(
            "gen_skill: no leaf covers " + ", ".join("docs/reference.md §" + d for d in dead)
            + "\n  add the anchor to a leaf's `sections` in tools/gen_skill.py\n")
        sys.exit(1)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if anything would change")
    args = ap.parse_args()
    files = build()
    os.makedirs(OUT, exist_ok=True)
    changed = []
    for name, text in files.items():
        path = os.path.join(OUT, name)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old != text:
            changed.append(name)
            if not args.check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if args.check:
        if changed:
            sys.stderr.write(
                "gen_skill: out of date: " + ", ".join(changed) + "\nRun `make skill`.\n")
            return 1
        print(f"  skill references up to date ({len(files)} leaves)")
        return 0
    print(f"  wrote {len(changed)} of {len(files)} leaves into {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())